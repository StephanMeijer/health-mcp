// Generates src/lib/api/tools.gen.ts from src/lib/api/tools.json (the server's tool list, kept current by the
// Rust test tests/tools_json.rs): one `ToolArgs` interface with every tool's arguments, plus which tools take `owner`.
import { readFile, writeFile } from 'node:fs/promises';
import { compile } from 'json-schema-to-typescript';

const dir = new URL('../src/lib/api/', import.meta.url);
const tools = JSON.parse(await readFile(new URL('tools.json', dir), 'utf8'));

// Every tool schema refers to its shared types as #/$defs/<Name>; merge them at the root. They come from the same
// Rust types, so equal names must mean equal schemas.
const defs = {};
const properties = {};
for (const t of tools) {
	const { $defs = {}, $schema, title, ...schema } = t.inputSchema;
	void $schema;
	for (const [name, def] of Object.entries($defs)) {
		if (defs[name] && JSON.stringify(defs[name]) !== JSON.stringify(def)) {
			throw new Error(`$defs.${name} differs between tools; rename one on the server`);
		}
		defs[name] = def;
	}
	properties[t.name] = {
		...schema,
		title: title ?? `${pascal(t.name)}Args`,
		description: t.description
	};
}

function pascal(name) {
	return name.replace(/(^|_)(\w)/g, (_, __, c) => c.toUpperCase());
}

const ts = await compile(
	{
		title: 'ToolArgs',
		type: 'object',
		properties,
		required: Object.keys(properties),
		additionalProperties: false,
		$defs: defs
	},
	'ToolArgs',
	{ bannerComment: '', additionalProperties: false, strictIndexSignatures: true, format: false }
);

const owner = tools.filter((t) => t.inputSchema.properties?.owner).map((t) => t.name);
const readOnly = tools.filter((t) => t.annotations?.readOnlyHint === true).map((t) => t.name);
const out = `// Generated by scripts/gen-tools.mjs from tools.json. Don't edit; run \`pnpm gen:tools\`.
/* eslint-disable */
${ts}
export type ToolName = keyof ToolArgs;

/** Tools that can run on a logbook shared with you (they take \`owner\`). */
export const ownerTools: ReadonlySet<ToolName> = new Set(${JSON.stringify(owner)});

/** Tools that only read. */
export const readOnlyTools: ReadonlySet<ToolName> = new Set(${JSON.stringify(readOnly)});
`;
await writeFile(new URL('tools.gen.ts', dir), out);
console.log(`tools.gen.ts: ${tools.length} tools, ${owner.length} take owner`);
